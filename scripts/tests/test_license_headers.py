SCRIPTS = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("license_headers", SCRIPTS / "license_headers.py")
headers = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(headers)


class HeaderTextTests(unittest.TestCase):
    def test_all_supported_formats_are_idempotent(self):
        for name in [f"sample{suffix}" for suffix in headers.STYLES] + [
            "Dockerfile.base", "Makefile", "Makefile.test",
        ]:
            with self.subTest(name=name):
                header = headers.header_for(name)
                original = "body\n"
                updated = headers.add_header(name, original, header)
                self.assertTrue(headers.has_header(name, updated, header))
                self.assertEqual(headers.add_header(name, updated, header), updated)
                self.assertTrue(updated.endswith(original))

    def test_shebang_encoding_and_crlf_preserved(self):
        original = "#!/usr/bin/python3\r\n# coding: utf-8\r\nprint('ok')\r\n"
        updated = headers.add_header("test.py", original, headers.HASH)
        self.assertTrue(updated.startswith("#!/usr/bin/python3\r\n# coding: utf-8\r\n"))
        self.assertTrue(headers.has_header("test.py", updated, headers.HASH))
        self.assertNotIn("\n", updated.replace("\r\n", ""))

    def test_second_line_encoding_cookie_without_shebang(self):
        original = "# example\n# -*- coding: utf-8 -*-\nprint('ok')\n"
        updated = headers.add_header("test.py", original, headers.HASH)
        self.assertEqual(updated.splitlines()[:2], original.splitlines()[:2])
        compile(updated, "<fixture>", "exec")

    def test_python_docstring_and_future_import(self):
        original = '"""Module docs."""\nfrom __future__ import annotations\n'
        updated = headers.add_header("test.py", original, headers.HASH)
        namespace = {}
        exec(compile(updated, "<fixture>", "exec"), namespace)
        self.assertEqual(namespace["__doc__"], "Module docs.")

    def test_docker_parser_directives(self):
        original = "# syntax=docker/dockerfile:1\n# escape=`\nFROM scratch\n"
        updated = headers.add_header("Dockerfile", original, headers.HASH)
        self.assertEqual(updated.splitlines()[:2], original.splitlines()[:2])
        self.assertTrue(headers.has_header("Dockerfile", updated, headers.HASH))

    def test_go_build_tags_remain_separated(self):
        original = "//go:build linux\n// +build linux\n\npackage fixture\n"
        updated = headers.add_header("test.go", original, headers.SLASH)
        self.assertTrue(updated.endswith("\n\n" + original))

    def test_html_frontmatter_and_template_definitions_stay_first(self):
        for prefix in [
            "---\ntitle: Example\n---\n",
            '+++\ntitle = "Example"\n+++\n',
            '{{ define "main" }}\n',
        ]:
            with self.subTest(prefix=prefix):
                original = prefix + "<p>Example</p>\n"
                header = headers.header_for("site/example.html")
                updated = headers.add_header("site/example.html", original, header)
                self.assertTrue(updated.startswith(prefix))
                self.assertTrue(headers.has_header("site/example.html", updated, header))
                self.assertEqual(
                    headers.add_header("site/example.html", updated, header), updated
                )

    def test_unclosed_html_frontmatter_requires_review(self):
        with self.assertRaisesRegex(ValueError, "frontmatter"):
            headers.add_header(
                "site/example.html", "---\ntitle: Example\n",
                headers.header_for("site/example.html"),
            )

    def test_empty_file_and_shebang_without_newline(self):
        self.assertTrue(headers.has_header(
            "test.py", headers.add_header("test.py", "", headers.HASH), headers.HASH
        ))
        updated = headers.add_header("test.sh", "#!/bin/sh", headers.HASH)
        self.assertTrue(updated.startswith("#!/bin/sh\n# Copyright"))

    def test_existing_notices_are_not_replaced(self):
        for original in [
            "# Copyright (c) Other Authors\nprint('ok')\n",
            "# SPDX-License-Identifier: Apache-2.0\nprint('ok')\n",
            "# Licensed under another license.\nprint('ok')\n",
            "# Copyright (c) Microsoft Corporation.\nprint('ok')\n",
            "// Code generated by another tool. DO NOT EDIT.\n",
        ]:
            with self.subTest(original=original):
                with self.assertRaisesRegex(ValueError, "provenance"):
                    headers.add_header("test.py", original, headers.HASH)

    def test_header_strings_in_code_are_not_accepted(self):
        text = f'COPYRIGHT = "{headers.COPYRIGHT}"\nLICENSE = "{headers.LICENSE}"\n'
        self.assertFalse(headers.has_header("test.py", text, headers.HASH))

    def test_non_source_and_protected_paths(self):
        for name in ["config.json", "values.yaml", "README.md", "go.mod", "go.sum", "asset.png"]:
            self.assertIsNone(headers.header_for(name))
        for path in [
            "app/node_modules/a.js", "scripts/__pycache__/cache.py",
            "app/.config/example.py", ".git/hooks/helper.py",
            ".github/.private/credential.py", "site/vendor/template.html",
            *headers.EXCLUSIONS,
        ]:
            with self.subTest(path=path):
                self.assertIsNotNone(headers.exclusion_reason(path))
        for path in [
            "scripts/check-ci.py", "scripts/cetirun-helm-release.sh",
            "scripts/e2e-test.sh", "app/cetirun-operator/test/deploy-instance.sh",
            ".github/scripts/check.py", "docs/example.py", "site/example.js",
            "Makefile", "app/cetirun-portal/Makefile", "new-component/main.go",
        ]:
            with self.subTest(path=path):
                self.assertIsNone(headers.exclusion_reason(path))
                self.assertIsNotNone(headers.header_for(path))


class RepositoryTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="cetirun-license-test-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / "LICENSE").write_text("MIT fixture\n")
        for directory in headers.REQUIRED_DIRS:
            (self.root / directory).mkdir()

    def put(self, relative, content):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content if isinstance(content, bytes) else content.encode())
        return path

    def run_headers(self, mode, *args):
        output = io.StringIO()
        with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
            result = headers.run(mode, ["--root", str(self.root), *args])
        return result, output.getvalue()

    def git(self, *args):
        return subprocess.run(
            ["git", "-C", str(self.root), *args], check=True,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        )

    def test_check_add_dry_run_and_idempotence(self):
        path = self.put("app/example.py", "print('ok')\n")
        path.chmod(0o755)
        original = path.read_bytes()
        self.assertEqual(self.run_headers("check")[0], 1)
        self.assertEqual(self.run_headers("add", "--dry-run")[0], 0)
        self.assertEqual(path.read_bytes(), original)
        self.assertEqual(self.run_headers("add", "--confirm-first-party")[0], 0)
        self.assertEqual(path.stat().st_mode & 0o777, 0o755)
        self.assertEqual(self.run_headers("check")[0], 0)
        added = path.read_bytes()
        self.assertIn("0 header(s) added", self.run_headers("add", "--confirm-first-party")[1])
        self.assertEqual(path.read_bytes(), added)

    def test_utf8_bom_preserved(self):
        path = self.put("scripts/example.py", headers.UTF8_BOM + b"#!/usr/bin/python3\n")
        self.assertEqual(self.run_headers("add", "--confirm-first-party")[0], 0)
        self.assertTrue(path.read_bytes().startswith(headers.UTF8_BOM + b"#!"))
        self.assertEqual(self.run_headers("check")[0], 0)

    def test_conflict_blocks_all_writes(self):
        path = self.put("app/a.py", "pass\n")
        self.put("app/z.py", "# Copyright Other Authors\npass\n")
        result, output = self.run_headers("add", "--confirm-first-party")
        self.assertEqual(result, 1)
        self.assertIn("provenance review", output)
        self.assertEqual(path.read_text(), "pass\n")

    def test_invalid_encoding_or_binary_is_failure_not_skip(self):
        for content in [b"\xff", b"binary\0data"]:
            self.put("app/a.py", content)
            self.assertEqual(self.run_headers("check")[0], 1)

    def test_exclusions_and_symlinks_are_not_read_or_written(self):
        good = self.put("app/a.py", "pass\n")
        protected = [
            self.put("app/node_modules/dependency.js", "untouched\n"),
            self.put("app/.private/credential.py", "untouched\n"),
            self.put("app/cetirun-chart/templates/_helpers.tpl", "untouched\n"),
            self.put("site/vendor/template.html", "untouched\n"),
            self.put(".github/.private/credential.py", "untouched\n"),
        ]
        external = tempfile.TemporaryDirectory(prefix="cetirun-license-external-")
        self.addCleanup(external.cleanup)
        outside = Path(external.name) / "outside.py"
        outside.write_text("untouched\n")
        (self.root / "app/link.py").symlink_to(outside)
        (self.root / "app/linked-dir").symlink_to(external.name, target_is_directory=True)
        self.assertEqual(self.run_headers("add", "--confirm-first-party")[0], 0)
        self.assertNotEqual(good.read_text(), "pass\n")
        for path in [outside, *protected]:
            self.assertEqual(path.read_text(), "untouched\n")
        self.assertTrue((self.root / "app/link.py").is_symlink())

    def test_git_tracks_ignored_sources_but_skips_untracked_ignored_files(self):
        self.git("init", "-q")
        self.put(".gitignore", "ignored.py\n")
        self.put("app/ignored.py", "pass\n")
        self.put("infra/ignored.py", "untracked\n")
        self.put("scripts/new.py", "pass\n")
        self.git("add", "-f", "app/ignored.py")
        self.assertEqual(
            [path for path, _ in headers.source_files(self.root)],
            ["app/ignored.py", "scripts/new.py"],
        )
        self.assertEqual(self.run_headers("add", "--confirm-first-party")[0], 0)
        self.assertEqual((self.root / "infra/ignored.py").read_text(), "untracked\n")

    def test_new_first_party_files_in_each_root_require_headers(self):
        self.put("app/existing.py", "\n".join(headers.HASH) + "\n\npass\n")
        self.assertEqual(self.run_headers("check")[0], 0)
        for relative, content in [
            ("app/new-component/main.go", "package component\n"),
            ("infra/new-module/main.bicep", "param name string\n"),
            ("scripts/new-ci-helper.py", "print('offline')\n"),
        ]:
            with self.subTest(relative=relative):
                path = self.put(relative, content)
                result, output = self.run_headers("check")
                self.assertEqual(result, 1)
                self.assertIn(relative, output)
                path.write_text(headers.add_header(
                    relative, content, headers.header_for(relative)
                ))
                self.assertEqual(self.run_headers("check")[0], 0)

    def test_repository_wide_check_and_adder_in_git_and_source_exports(self):
        paths = [
            "scripts/cetirun-helm-release.sh",
            "scripts/istio-helm-release.sh",
            "scripts/operator-helm-release.sh",
            "scripts/portal-helm-release.sh",
            "scripts/e2e-test.sh",
            "app/cetirun-operator/test/deploy-instance.sh",
            "Makefile",
            "app/cetirun-operator/Makefile",
            "app/cetirun-portal/Makefile",
            "docs/example.py",
            "site/example.js",
            ".github/scripts/check.py",
            "new-component/main.go",
        ]
        for use_git in (False, True):
            with self.subTest(use_git=use_git):
                if use_git:
                    self.git("init", "-q")
                for relative in paths:
                    self.put(relative, "body\n")
                if use_git:
                    self.git("add", "Makefile", "scripts/cetirun-helm-release.sh")
                result, output = self.run_headers("check")
                self.assertEqual(result, 1)
                for relative in paths:
                    self.assertIn(relative + ": missing", output)
                self.assertEqual(self.run_headers("add", "--dry-run")[0], 0)
                for relative in paths:
                    self.assertEqual((self.root / relative).read_text(), "body\n")
                self.assertEqual(self.run_headers("add", "--confirm-first-party")[0], 0)
                self.assertEqual(self.run_headers("check")[0], 0)

    def test_linked_git_worktree_with_new_untracked_source(self):
        self.git("init", "-q")
        self.put("app/existing.py", "\n".join(headers.HASH) + "\n\npass\n")
        self.git("add", "LICENSE", "app/existing.py")
        self.git(
            "-c", "core.hooksPath=/dev/null", "-c", "commit.gpgSign=false",
            "-c", "user.name=Offline Test", "-c", "user.email=test@example.invalid",
            "commit", "-qm", "Fixture",
        )
        worktree = self.root / "linked-worktree"
        self.git("worktree", "add", "--detach", str(worktree), "HEAD")
        (worktree / "infra").mkdir()
        (worktree / "scripts").mkdir()
        (worktree / "scripts/new-helper.py").write_text("pass\n")
        self.assertTrue((worktree / ".git").is_file())
        with contextlib.redirect_stderr(io.StringIO()) as output:
            self.assertEqual(headers.check_headers(["--root", str(worktree)]), 1)
        self.assertIn("scripts/new-helper.py", output.getvalue())

    def test_list_exclusions_is_read_only_for_both_entrypoints(self):
        self.put("app/a.py", "pass\n")
        for mode in ["check", "add"]:
            result, output = self.run_headers(mode, "--list-exclusions")
            self.assertEqual(result, 0)
            for relative in headers.EXCLUSIONS:
                self.assertIn(relative, output)
            self.assertNotIn("deferred", output)
            self.assertEqual((self.root / "app/a.py").read_text(), "pass\n")

    def test_symlink_source_root_is_rejected(self):
        (self.root / "infra").rmdir()
        (self.root / "infra").symlink_to(self.root / "app", target_is_directory=True)
        self.assertEqual(self.run_headers("check")[0], 2)

    def test_git_failure_does_not_fall_back_to_a_partial_scan(self):
        self.git("init", "-q")
        self.put("app/a.py", "pass\n")
        with mock.patch.object(
            headers, "git_files", side_effect=subprocess.CalledProcessError(128, "git")
        ):
            self.assertEqual(self.run_headers("check")[0], 2)

    def test_explicit_root_ignores_caller_working_directory(self):
        self.put("app/example.py", "pass\n")
        result = subprocess.run(
            [sys.executable, str(SCRIPTS / "check-license-headers.py"),
             "--root", str(self.root)],
            cwd="/", capture_output=True, text=True,
        )
        self.assertEqual(result.returncode, 1)
        self.assertIn("app/example.py", result.stderr)

    def test_default_root_is_script_relative(self):
        self.assertEqual(headers.DEFAULT_ROOT, SCRIPTS.parent)

    def test_invalid_root_and_empty_scope_fail(self):
        self.assertEqual(self.run_headers("check")[0], 2)
        (self.root / "infra").rmdir()
        self.assertEqual(self.run_headers("check")[0], 2)

    def test_concurrent_change_is_not_overwritten(self):
        path = self.put("app/example.py", "pass\n")
        original_add = headers.add_header

        def concurrent_add(*args):
            path.write_text("other agent's work\n")
            return original_add(*args)

        with mock.patch.object(headers, "add_header", side_effect=concurrent_add):
            self.assertEqual(self.run_headers("add", "--confirm-first-party")[0], 2)
        self.assertEqual(path.read_text(), "other agent's work\n")

    def test_help_and_bad_arguments_for_every_entrypoint(self):
        for script in ["license_headers.py", "check-license-headers.py", "add-license-headers.py"]:
            for argument, status in [("--help", 0), ("--unknown-option", 2)]:
                with self.subTest(script=script, argument=argument):
                    result = subprocess.run(
                        [sys.executable, str(SCRIPTS / script), argument],
                        capture_output=True, text=True,
                    )
                    self.assertEqual(result.returncode, status)

    def test_adder_requires_authorship_confirmation(self):
        with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit) as error:
            headers.add_headers(["--root", str(self.root)])
        self.assertEqual(error.exception.code, 2)


